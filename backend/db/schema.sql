CREATE SCHEMA IF NOT EXISTS LEDGERMIND;

CREATE TABLE IF NOT EXISTS LEDGERMIND.USERS (
    ID VARCHAR(30) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL,
    NAME VARCHAR(255),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS LEDGERMIND.ACCOUNTS (
    ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(30) NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    BANK_NAME VARCHAR(255),
    ACCOUNT_LAST4 VARCHAR(4),
    ACCOUNT_TYPE VARCHAR(20) DEFAULT 'SAVINGS',
    IFSC VARCHAR(20),
    BRANCH VARCHAR(255),
    CURRENCY VARCHAR(3) DEFAULT 'INR',
    NICKNAME VARCHAR(255),
    IS_PRIMARY BOOLEAN DEFAULT FALSE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS LEDGERMIND.ENTITIES (
    ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(30) NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    ENTITY_TYPE VARCHAR(20) DEFAULT 'UNKNOWN',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS LEDGERMIND.ENTITY_ALIASES (
    ID VARCHAR(30) NOT NULL,
    ENTITY_ID VARCHAR(30) NOT NULL,
    ALIAS VARCHAR(255) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS LEDGERMIND.ENTITY_IDENTIFIERS (
    ID VARCHAR(30) NOT NULL,
    ENTITY_ID VARCHAR(30) NOT NULL,
    IDENTIFIER_TYPE VARCHAR(30) NOT NULL,
    IDENTIFIER_VALUE VARCHAR(255) NOT NULL,
    RAW_VALUE VARCHAR(255) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS LEDGERMIND.ENTITY_MATCH_DECISIONS (
    ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(30) NOT NULL,
    ENTITY_ID VARCHAR(30) NOT NULL,
    ALIAS VARCHAR(255) NOT NULL,
    DECISION VARCHAR(20) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS LEDGERMIND.FINANCIAL_EVENTS (
    ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(30) NOT NULL,
    ENTITY_ID VARCHAR(30),
    AMOUNT DECIMAL(18,2) NOT NULL,
    DIRECTION VARCHAR(10) NOT NULL,
    TX_STATUS VARCHAR(20) NOT NULL,
    OCCURRED_AT TIMESTAMP NOT NULL,
    DESCRIPTION VARCHAR(2000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS LEDGERMIND.TRANSACTION_RECORDS (
    ID VARCHAR(30) NOT NULL,
    FINANCIAL_EVENT_ID VARCHAR(30) NOT NULL,
    ACCOUNT_ID VARCHAR(30),
    SOURCE_TYPE VARCHAR(30) NOT NULL,
    SOURCE_REFERENCE VARCHAR(255),
    RAW_ROW_HASH VARCHAR(128),
    RAW_DESCRIPTION VARCHAR(2000),
    AMOUNT DECIMAL(18,2) NOT NULL,
    DIRECTION VARCHAR(10) NOT NULL,
    TX_STATUS VARCHAR(20) NOT NULL,
    OCCURRED_AT TIMESTAMP NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS LEDGERMIND.STATEMENT_IMPORTS (
    ID VARCHAR(30) NOT NULL,
    USER_ID VARCHAR(30) NOT NULL,
    ACCOUNT_ID VARCHAR(30),
    SOURCE_TYPE VARCHAR(30) NOT NULL,
    FILE_NAME VARCHAR(500),
    FILE_HASH VARCHAR(128) NOT NULL,
    PARSED_COUNT INT DEFAULT 0,
    IMPORTED_COUNT INT DEFAULT 0,
    SKIPPED_COUNT INT DEFAULT 0,
    FLAGGED_COUNT INT DEFAULT 0,
    IMPORT_STATUS VARCHAR(20) DEFAULT 'PENDING',
    STARTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    PRIMARY KEY (ID)
);
